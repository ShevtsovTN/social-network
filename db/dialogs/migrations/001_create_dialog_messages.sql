-- Сообщения диалогов (ДЗ «Шардинг диалогов»). Живут в отдельном кластере Citus, а не в основном PostgreSQL;
-- файл выполняется на координаторе (social-network-docker/citus/cluster-init.sh).
--
-- - dialog_id — ключ шардирования: детерминированный UUID пары участников, одинаковый для обоих направлений.
--   Вся переписка двоих лежит в одном шарде, поэтому отправка и чтение диалога идут ровно на один воркер.
--   Ключ по паре, а не по отправителю или получателю, расходит сообщения очень активного пользователя
--   по шардам вместе с его диалогами («эффект Леди Гаги»).
-- - id — UUIDv7 из приложения: порядок id совпадает с хронологией, он же курсор пагинации.
-- - Первичный ключ (dialog_id, id) обслуживает и выборку страницы диалога, и её сортировку, поэтому других
--   индексов нет. Citus требует, чтобы первичный ключ распределённой таблицы включал ключ шардирования;
--   он же нужен логической репликации при переносе шардов (replica identity).
-- - Внешних ключей на users нет: пользователи лежат в другой базе. Получателя проверяет приложение.
-- - CHECK дублирует правила домена: нельзя писать самому себе и отправлять пустой текст.
CREATE TABLE dialog_messages (
    dialog_id    UUID          NOT NULL,
    id           UUID          NOT NULL,
    sender_id    UUID          NOT NULL,
    recipient_id UUID          NOT NULL,
    text         VARCHAR(2000) NOT NULL CHECK (btrim(text) <> ''),
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    PRIMARY KEY (dialog_id, id),
    CHECK (sender_id <> recipient_id)
);

-- 64 логических шарда с запасом на рост числа воркеров: переносить шарды можно под нагрузкой,
-- а изменение их количества (alter_distributed_table) блокирует запись.
SELECT create_distributed_table('dialog_messages', 'dialog_id', shard_count => 64);
